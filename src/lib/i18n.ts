const DICTS: Record<Lang, Record<MessageKey, string>> = { fr, en };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

/**
 * Builds the translate function for a language. Safe in both Server and Client
 * Components (it is a plain function over a plain object).
 *
 * Plural hint: French and English both use "(s)" in these strings, except where
 * a real plural matters; `t` keeps it simple and predictable for a front desk.
 */
export function translator(lang: Lang): Translate {
  const dict = DICTS[lang] ?? DICTS[DEFAULT_LANG];
  return (key, vars) => {
    let text = dict[key] ?? DICTS[DEFAULT_LANG][key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.split(`{${name}}`).join(String(value));
      }
    }
    return text;
  };
}

export function isLang(value: unknown): value is Lang {
  return value === "fr" || value === "en";
}
